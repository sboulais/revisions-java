package revisions.chapitre5;

/**
 * Une interface fonctionnelle est une interface qui ne contient qu'une seule méthode abstraite.
 * Les interfaces fonctionnelles sont utilisées pour représenter des fonctions ou des comportements dans le code.
 * Elles sont souvent utilisées avec des expressions lambda ou des références de méthode pour fournir une implément.
 */
public interface Printer {
    void print(String message);
}
